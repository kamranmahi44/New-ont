private val DarkColorScheme = darkColorScheme(
    primary = CyberCyanLight,
    onPrimary = DarkBackground,
    primaryContainer = CyberCyanDark,
    onPrimaryContainer = TextPrimary,
    secondary = IndigoLight,
    onSecondary = DarkBackground,
    secondaryContainer = IndigoAccent,
    onSecondaryContainer = TextPrimary,
    tertiary = EmeraldOnline,
    onTertiary = DarkBackground,
    background = DarkBackground,
    onBackground = TextPrimary,
    surface = DarkSurface,
    onSurface = TextPrimary,
    surfaceVariant = DarkSurfaceElevated,
    onSurfaceVariant = TextSecondary,
    outline = DarkSurfaceBorder,
    error = RoseBlocked,
    onError = TextPrimary
)

private val LightColorScheme = darkColorScheme(
    primary = CyberCyan,
    onPrimary = TextPrimary,
    primaryContainer = CyberCyanLight,
    onPrimaryContainer = DarkBackground,
    secondary = IndigoAccent,
    onSecondary = TextPrimary,
    tertiary = EmeraldOnline,
    background = DarkBackground,
    onBackground = TextPrimary,
    surface = DarkSurface,
    onSurface = TextPrimary,
    surfaceVariant = DarkSurfaceElevated,
    onSurfaceVariant = TextSecondary,
    outline = DarkSurfaceBorder,
    error = RoseBlocked
)

@Composable
fun MyApplicationTheme(
    darkTheme: Boolean = true, // Network admin app looks exceptional in dark cyber mode
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicDarkColorScheme(context)
        }
        else -> DarkColorScheme
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window
            if (window != null) {
                window.statusBarColor = DarkBackground.toArgb()
                window.navigationBarColor = DarkBackground.toArgb()
                WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = false
                WindowCompat.getInsetsController(window, view).isAppearanceLightNavigationBars = false
            }
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}
